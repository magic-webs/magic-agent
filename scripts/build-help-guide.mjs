import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docs = process.argv[2] ?? join(root, "..", "magic-agent-docs");
const out = join(root, "convex", "lib", "helpGuide.ts");

const nav = JSON.parse(readFileSync(join(docs, "docs.json"), "utf8")).navigation;

function clean(source) {
  const match = source.match(/^---\n([\s\S]*?)\n---\n?/);
  const front = match?.[1] ?? "";
  const title = front.match(/^title:\s*"?(.*?)"?\s*$/m)?.[1] ?? "";
  const body = (match ? source.slice(match[0].length) : source)
    .replace(/\r/g, "")
    .replace(/^import .*$/gm, "")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/<img[^>]*\/?>/g, "")
    .replace(/<(Step|Card|Tab)\b[^>]*title="([^"]*)"[^>]*>/g, "\n**$2**\n")
    .replace(/<(Note|Tip|Warning)>/g, "\n$1: ")
    .replace(/<\/?[A-Z][A-Za-z]*\b[^>]*>/g, "")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/^[ \t]+/gm, "")
    .replace(/^(#+) /gm, "##$1 ")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { title, body };
}

const parts = [];
for (const tab of nav.tabs) {
  parts.push(`# ${tab.tab}`);
  for (const group of tab.groups) {
    parts.push(`## ${group.group}`);
    for (const page of group.pages) {
      const { title, body } = clean(readFileSync(join(docs, `${page}.mdx`), "utf8"));
      parts.push(`### ${title}\n\n${body}`);
    }
  }
}

const guide = parts.join("\n\n");
writeFileSync(
  out,
  `// Generated by scripts/build-help-guide.mjs from magic-agent-docs. Do not edit.\nexport const HELP_GUIDE = ${JSON.stringify(guide)};\n`
);
console.log(`helpGuide.ts: ${guide.length} chars`);
